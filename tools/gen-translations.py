#!/usr/bin/env python3
"""Build packages/maprisma_playground_core/lib/src/translations.g.dart from translations/<code>.json
(AI Playground's catalogs, English text -> translation) and translations/extra/<code>.json (the
texts Maprisma Playground added). Run after changing a catalog: python3 tools/gen-translations.py"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
codes = ["de", "fr", "es", "it", "pt", "nl", "pl"]
out = ["// Generated by tools/gen-translations.py from translations/*.json: do not edit.", "",
       "const Map<String, String> translationCatalogs = {"]
for code in codes:
    merged = json.loads((root / "translations" / f"{code}.json").read_text(encoding="utf-8"))
    extra = root / "translations" / "extra" / f"{code}.json"
    if extra.exists():
        merged.update(json.loads(extra.read_text(encoding="utf-8")))
    merged = {k: v for k, v in merged.items() if isinstance(k, str) and isinstance(v, str) and v}
    text = json.dumps(merged, ensure_ascii=False, sort_keys=True)
    literal = json.dumps(text, ensure_ascii=False).replace("$", "\\$")   # no Dart interpolation
    out.append(f"  {json.dumps(code)}: {literal},")
out.append("};")
target = root / "packages/maprisma_playground_core/lib/src/translations.g.dart"
target.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{target.relative_to(root)}: {', '.join(codes)}")
